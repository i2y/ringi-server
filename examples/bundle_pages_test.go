// leaveV3 reads the examples' bundle of version 3 of the leave requests (regen.sh writes it).
func leaveV3(t testing.TB) []byte {
	t.Helper()
	b, err := os.ReadFile("bundles/leave-v3.zip")
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// uploadBundle posts the bundles' page's form with a bundle, as a browser does.
func (a adminAs) uploadBundle(at string, archive []byte) *httptest.ResponseRecorder {
	var b bytes.Buffer
	mw := multipart.NewWriter(&b)
	mw.WriteField("_at", at)
	fw, _ := mw.CreateFormFile("bundle", "leave-v3.zip")
	fw.Write(archive)
	mw.Close()
	r := httptest.NewRequest("POST", "/pages/admin/bundles?lang=en", &b)
	r.Header.Set("Content-Type", mw.FormDataContentType())
	r.Header.Set("X-Person", a.person)
	r.Header.Set("X-Roles", a.roles)
	r.Header.Set("Sec-Fetch-Site", "same-origin")
	w := httptest.NewRecorder()
	a.h.ServeHTTP(w, r)
	return w
}

// TestBundlePagesWithoutScript: the bundles' pages of the examples' server, as a browser with no
// script uses them (the framework's DESIGN 15). The bundle is the examples' own, of version 3 of the
// leave requests, which the server reads with wasmkind: its vectors run on its Wasm as it is checked.
//
// One of the staff has no page of them. The administrator of human resources, who owns leave,
// uploads it: the server checks it, and shows what version 3 changes from version 2, the field the
// API takes marked, and the text ritsu wrote into it; they may not decide it themselves. The
// administrator of accounting sees neither it nor an upload of it. The administrator of the whole
// approves it only once they tick that they checked the API changes, and then it is served: the
// versions' page has a switch of version 3. The same bundle uploaded again adds nothing, and the
// record lists the bundle's lines.
func TestBundlePagesWithoutScript(t *testing.T) {
	at := time.Date(2026, 11, 16, 10, 0, 0, 0, Zone)
	archive := leaveV3(t)
	clock := servertest.NewClock(at)
	_, h := newWeb(t, webSetup{Store: memstore.New(), At: at, Clock: clock, Gate: &Gate{}, Config: func(c *server.Config) {
		c.Packages = append(c.Packages, version2(t))
		c.LoadBundle = wasmkind.Load
	}})
	staff := adminAs{t, h, "e1201", "staff"}
	hr := adminAs{t, h, "e6001", "workflow_admin"}
	accounting := adminAs{t, h, "e1001", "workflow_admin"}
	whole := adminAs{t, h, "e7001", "system_admin"}

	if w := staff.get("/pages/admin/bundles"); w.Code != 404 {
		t.Errorf("the bundles to one of the staff: %d", w.Code)
	}
	if w := whole.get("/pages/admin/?lang=en"); !strings.Contains(w.Body.String(), `href="/pages/admin/bundles?lang=en"`) {
		t.Errorf("the administration does not link to the bundles: %d", w.Code)
	}
	page := hr.get("/pages/admin/bundles?lang=en").Body.String()
	action, values := formOn(t, page, "upload", "/pages/admin/bundles")
	if action == "" || !strings.Contains(page, "No bundles.") {
		t.Fatalf("the bundles' page of an administrator of human resources: %.800s", page)
	}

	// uploaded and checked: what changes, and no form to decide it for the one who uploaded it
	to, w := hr.follow(hr.uploadBundle(values.Get("_at"), archive))
	page = w.Body.String()
	digest := strings.TrimPrefix(strings.Split(to, "?")[0], "/pages/admin/bundles/")
	for _, want := range []string{
		"The bundle was uploaded and checked: another administrator decides it.",
		"Waiting to be decided", "leave Version 3", "leave_ja Version 3", "What changes from version 2:",
		`class="api"`, "changes the API", "The text the bundle held (written by <code>ritsu ringi diff</code> against version 2)",
		// the lines of the difference, by the fields' labels, with the API's names as code
		"The field &#34;How to reach you while away&#34; (contact) is added", "In the request body of <code>submit_leave</code>, <code>form.contact</code> is added",
		// the text the bundle held, as HTML: its headings and tables, with no comment of it
		"<h3>Leave request: what changes</h3>", "<h4>Form</h4>", `<th scope="col">Before</th>`, "<td>How to reach you while away</td>",
		"Once approved, new requests take it from 2028-04-01", "You uploaded this bundle: another administrator decides it.",
	} {
		if !strings.Contains(page, want) {
			t.Errorf("the page of the bundle uploaded says no %q", want)
		}
	}
	if strings.Contains(page, "Generated by ringi") || strings.Contains(page, "| What |") {
		t.Error("the page shows the text the bundle held as Markdown")
	}
	if len(digest) != 64 || strings.Contains(page, `class="admin decide"`) {
		t.Errorf("the page of the bundle uploaded: %s, a form to decide it", to)
	}
	if w := hr.post("/pages/admin/bundles/"+digest, url.Values{"_do": {"approve"}, "_at": {"x"}}); w.Code == http.StatusSeeOther {
		t.Errorf("the one who uploaded the bundle approves it: %d", w.Code)
	}

	// the administrator of accounting: not their department's
	if w := accounting.get("/pages/admin/bundles/" + digest); w.Code != 404 {
		t.Errorf("the bundle of leave to an administrator of accounting: %d", w.Code)
	}
	if w := accounting.uploadBundle("x", archive); w.Code != 404 || !strings.Contains(w.Body.String(), "you may not upload") {
		t.Errorf("an upload of leave by an administrator of accounting: %d", w.Code)
	}

	// the administrator of the whole: no approval with the API changes unticked
	page = whole.get("/pages/admin/bundles/" + digest + "?lang=en").Body.String()
	action, values = formOn(t, page, "decide", "/pages/admin/bundles/"+digest)
	if action == "" || values.Get("difference") == "" || !strings.Contains(page, "I checked that the API changes") {
		t.Fatalf("the form to decide the bundle: %q %v", action, values)
	}
	values.Set("_do", "approve")
	if w := whole.post(action, values); w.Code != http.StatusConflict || !strings.Contains(w.Body.String(), "tick that you checked it") {
		t.Errorf("an approval with the API changes unticked: %d", w.Code)
	}
	values.Set("api_changes", "yes")
	values.Set("reason", "The contact while away, from April")
	to, w = whole.follow(whole.post(action, values))
	if !strings.Contains(to, "done=approved") || !strings.Contains(w.Body.String(), "Approved: served") || !strings.Contains(w.Body.String(), "The contact while away, from April") {
		t.Errorf("after the approval: %s %d", to, w.Code)
	}
	if page := whole.get("/pages/admin/kinds?lang=en").Body.String(); !strings.Contains(page, "/pages/admin/kinds/leave/versions/3") {
		t.Errorf("the versions' page has no switch of version 3 of leave")
	}

	// the same bundle again, from the page read a minute later: nothing added
	clock.Add(time.Minute)
	page = hr.get("/pages/admin/bundles?lang=en").Body.String()
	_, values = formOn(t, page, "upload", "/pages/admin/bundles")
	if to, w := hr.follow(hr.uploadBundle(values.Get("_at"), archive)); !strings.Contains(to, "done=kept") || !strings.Contains(w.Body.String(), "nothing was added") {
		t.Errorf("the same bundle uploaded again: %s %d", to, w.Code)
	}
	if w := whole.get("/pages/admin/records?what=bundle&lang=en"); w.Code != 200 || !strings.Contains(w.Body.String(), digest[:12]) {
		t.Errorf("the record of the bundles: %d %.500s", w.Code, w.Body.String())
	}
}

// TestBundleAtStart: the examples' bundle in Config.Bundles (the server's -bundles) is checked as
// the server starts, kept approved as read at start, and served: a request of leave on 2028-11-13
// takes version 3, whose form has the field the bundle adds, and the screens' files of the newest
// version are the bundle's. A second server on the same store reads it from the store.
func TestBundleAtStart(t *testing.T) {
	store := memstore.New()
	at := time.Date(2028, 11, 13, 9, 0, 0, 0, Zone)
	functions := fileOfZip(t, leaveV3(t), "a2ui/functions.js")
	for i := range 2 {
		srv, h := newWeb(t, webSetup{Store: store, At: at, Config: func(c *server.Config) {
			c.Packages = append(c.Packages, version2(t))
			c.LoadBundle = wasmkind.Load
			c.Bundles = []server.BundleFile{{Name: "leave-v3.zip", Archive: leaveV3(t)}}
		}})
		if gone, err := srv.Unpackaged(context.Background()); err != nil || len(gone) > 0 {
			t.Fatalf("server %d: %v %v", i+1, gone, err)
		}
		if v, ok := srv.Current("leave", at); !ok || v != 3 {
			t.Errorf("server %d: a request of leave takes version %d (%v); want 3", i+1, v, ok)
		}
		if w := browse(h, "GET", "/pages/requests/leave/new?lang=en", "e1201", nil); w.Code != 200 || !strings.Contains(w.Body.String(), "How to reach you while away") {
			t.Errorf("server %d: the form of leave: %d, without the field of version 3", i+1, w.Code)
		}
		if w := send(h, "GET", "/a2ui/functions.js", "", nil); w.Code != 200 || !bytes.Equal(w.Body.Bytes(), functions) {
			t.Errorf("server %d: /a2ui/functions.js: %d, not the bundle's", i+1, w.Code)
		}
	}
	bs, err := store.Bundles(context.Background())
	if err != nil || len(bs) != 1 || bs[0].State != "approved" || bs[0].Source != "start" {
		t.Errorf("the store keeps %+v (%v)", bs, err)
	}
}

// fileOfZip reads a file of a zip.
func fileOfZip(t testing.TB, archive []byte, name string) []byte {
	t.Helper()
	zr, err := zip.NewReader(bytes.NewReader(archive), int64(len(archive)))
	if err != nil {
		t.Fatal(err)
	}
	f, err := zr.Open(name)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	b, err := io.ReadAll(f)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// TestBundlesDocument: what docs/bundles.md (and its Japanese) shows of the examples' bundle is what
// the server answers now: the upload's answer, the approval's, the uploader's refusal, and the
// digests and the vectors in the commands and the log. A bundle made again, or a difference written
// otherwise, changes them: run the commands of the document again, and paste what they print.
func TestBundlesDocument(t *testing.T) {
	archive := leaveV3(t)
	_, h := newWeb(t, webSetup{Store: memstore.New(), At: time.Date(2026, 11, 26, 19, 49, 0, 0, Zone), Config: func(c *server.Config) {
		c.Packages = append(c.Packages, version2(t))
		c.LoadBundle = wasmkind.Load
	}})
	w := send(h, "POST", "/admin/bundles/uploads", "e6001", archive, "Content-Type", "application/zip",
		"Idempotency-Key", "leave-v3", "X-Roles", "workflow_admin")
	var up struct {
		Digest string `json:"digest"`
		State  string `json:"state"`
		Adds   []struct {
			Name    string `json:"name"`
			Version int    `json:"version"`
		} `json:"adds"`
		Checks struct {
			Vectors int `json:"vectors"`
			Worked  int `json:"worked"`
		} `json:"checks"`
		Difference struct {
			Digest     string `json:"digest"`
			APIChanges bool   `json:"api_changes"`
		} `json:"difference"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &up); err != nil || w.Code != 200 {
		t.Fatalf("the upload: %d %.300s", w.Code, w.Body.String())
	}
	refused := send(h, "POST", "/admin/bundles/"+up.Digest+"/approve", "e6001",
		[]byte(`{"digest": "`+up.Difference.Digest+`", "api_changes": true}`), "Content-Type", "application/json",
		"Idempotency-Key", "approve-leave-v3", "X-Roles", "workflow_admin")
	w = send(h, "POST", "/admin/bundles/"+up.Digest+"/approve", "e7001",
		[]byte(`{"digest": "`+up.Difference.Digest+`", "api_changes": true, "reason": "The contact while away, from April"}`),
		"Content-Type", "application/json", "Idempotency-Key", "approve-leave-v3", "X-Roles", "system_admin")
	var approved struct {
		State   string `json:"state"`
		Decided struct {
			Person string `json:"person"`
			Reason string `json:"reason"`
		} `json:"decided"`
		Difference struct {
			Kinds []struct {
				Name    string `json:"name"`
				Version int    `json:"version"`
				Starts  struct {
					Day string `json:"day"`
				} `json:"starts"`
			} `json:"kinds"`
		} `json:"difference"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &approved); err != nil || w.Code != 200 {
		t.Fatalf("the approval: %d %.300s", w.Code, w.Body.String())
	}
	// the lines as the document's jq writes them
	compact := func(v any) string {
		var b bytes.Buffer
		enc := json.NewEncoder(&b)
		enc.SetEscapeHTML(false)
		enc.Encode(v)
		return strings.TrimSpace(b.String())
	}
	type version struct {
		Name    string `json:"name"`
		Version int    `json:"version"`
	}
	type start struct {
		Name    string `json:"name"`
		Version int    `json:"version"`
		Day     string `json:"day"`
	}
	adds := []version{}
	for _, a := range up.Adds {
		adds = append(adds, version{a.Name, a.Version})
	}
	starts := []start{}
	for _, k := range approved.Difference.Kinds {
		starts = append(starts, start{k.Name, k.Version, k.Starts.Day})
	}
	lines := []string{
		compact(struct {
			Digest     string    `json:"digest"`
			State      string    `json:"state"`
			Adds       []version `json:"adds"`
			Checks     any       `json:"checks"`
			Difference any       `json:"difference"`
		}{up.Digest, up.State, adds, up.Checks, up.Difference}),
		compact(struct {
			State   string  `json:"state"`
			Decided any     `json:"decided"`
			Starts  []start `json:"starts"`
		}{approved.State, approved.Decided, starts}),
		strings.TrimSpace(refused.Body.String()),
	}
	said := map[string]string{
		"../docs/bundles.md":    fmt.Sprintf("ran %d events and %d forms", up.Checks.Vectors, up.Checks.Worked),
		"../docs/bundles.ja.md": fmt.Sprintf("%d のイベントと %d のフォーム", up.Checks.Vectors, up.Checks.Worked),
	}
	for path, counts := range said {
		doc, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		for _, want := range append(lines, counts,
			"/admin/bundles/"+up.Digest+"/approve",
			`"digest": "`+up.Difference.Digest+`"`,
			fmt.Sprintf("digest=%s adds=\"leave v3, leave_ja v3\" vectors=%d worked=%d", up.Digest[:12], up.Checks.Vectors, up.Checks.Worked),
		) {
			if !bytes.Contains(doc, []byte(want)) {
				t.Errorf("%s does not say what the server answers now: %s", path, want)
			}
		}
	}
}
