// TestWholeNumber checks the whole numbers the adapters read as the entries and the API's bodies
// do: a whole number in any spelling, and nothing that is not whole or not inside int64.
func TestWholeNumber(t *testing.T) {
	for _, c := range []struct {
		n    string
		want int64
		ok   bool
	}{
		{"20", 20, true}, {"20.0", 20, true}, {"2e1", 20, true}, {"2E+1", 20, true}, {"200e-1", 20, true},
		{"-3", -3, true}, {"0.000", 0, true}, {"9223372036854775807", 9223372036854775807, true},
		{"-9223372036854775808", -9223372036854775808, true},
		{"2.5", 0, false}, {"1e-1", 0, false}, {"9223372036854775808", 0, false}, {"1e19", 0, false},
	} {
		if v, ok := WholeNumber(json.Number(c.n)); v != c.want || ok != c.ok {
			t.Errorf("WholeNumber(%s) = %d, %v; want %d, %v", c.n, v, ok, c.want, c.ok)
		}
	}
}

// TestSaidAsTheEntries checks the sentence of each value of a body the framework does not take,
// in English and in Japanese, against the sentence the generated code says of the same value: the
// examples' leave and expense of screens/testdata, generated by the same ritsu in English and with
// --lang ja, and given each value in their argument (the submit of `start`, the event of `next`).
// The examples' own test (TestSameSentences) holds the English sentences to the generated entries
// themselves.
func TestSaidAsTheEntries(t *testing.T) {
	a, err := readAPI(os.DirFS("screens/testdata/requests"))
	if err != nil {
		t.Fatal(err)
	}
	form := `{"kind":"paid","first_day":"2026-12-21","days":8,"reason":"A family visit"}`
	submit := func(key, value string) string { return `{"form":` + with(form, key, value) + `}` }
	rev := `{"round":1,"stage":0,"edits":0}`
	approve := func(r string) string { return `{"revision":` + r + `}` }
	long := strings.Repeat("a", 45)
	for _, c := range []struct{ op, body, en, ja string }{
		{"submit_leave", submit("days", `"three"`),
			"The argument `submit.form.days` of `start` is \"three\", and must be an integer",
			"関数 `start` の引数 `submit.form.days` が \"three\" です。整数が要ります"},
		{"submit_leave", submit("days", `2.5`),
			"The argument `submit.form.days` of `start` is 2.5, and must be an integer",
			"関数 `start` の引数 `submit.form.days` が 2.5 です。整数が要ります"},
		{"submit_leave", submit("days", `1e30`),
			"The argument `submit.form.days` of `start` is outside int64",
			"関数 `start` の引数 `submit.form.days` が int64 の外にあります"},
		{"submit_leave", submit("days", `"abc\u3042def"`),
			"The argument `submit.form.days` of `start` is \"abc\u3042def\", and must be an integer",
			"関数 `start` の引数 `submit.form.days` が \"abc \u3042 def\" です。整数が要ります"},
		{"submit_leave", submit("days", `"`+long+`"`),
			"The argument `submit.form.days` of `start` is \"" + long[:40] + "\u2026\", and must be an integer",
			"関数 `start` の引数 `submit.form.days` が \"" + long[:40] + "\u2026\" です。整数が要ります"},
		{"submit_leave", submit("days", `"a\"b\\c\td\u0001e"`),
			"The argument `submit.form.days` of `start` is \"a\\\"b\\\\c\\td\\u0001e\", and must be an integer",
			"関数 `start` の引数 `submit.form.days` が \"a\\\"b\\\\c\\td\\u0001e\" です。整数が要ります"},
		{"submit_leave", submit("first_day", `"2026-13-40"`),
			"The argument `submit.form.first_day` of `start` is 2026-13-40, outside its range >=0001-01-01 <=9999-12-31",
			"関数 `start` の引数 `submit.form.first_day` の 2026-13-40 は、範囲 >=0001-01-01 <=9999-12-31 の外です"},
		{"submit_leave", submit("first_day", `"02026-13-05"`),
			"The argument `submit.form.first_day` of `start` is 2026-13-05, outside its range >=0001-01-01 <=9999-12-31",
			"関数 `start` の引数 `submit.form.first_day` の 2026-13-05 は、範囲 >=0001-01-01 <=9999-12-31 の外です"},
		{"submit_leave", submit("first_day", `"2026-4-1"`),
			"The argument `submit.form.first_day` of `start` is \"2026-4-1\", and must be a date written YYYY-MM-DD",
			"関数 `start` の引数 `submit.form.first_day` が \"2026-4-1\" です。YYYY-MM-DD と書いた日付が要ります"},
		{"submit_leave", submit("kind", `5`),
			"The argument `submit.form.kind` of `start` is 5, and must be a string",
			"関数 `start` の引数 `submit.form.kind` が 5 です。文字列が要ります"},
		{"submit_leave", submit("reason", `[]`),
			"The argument `submit.form.reason` of `start` is an array, and must be a string",
			"関数 `start` の引数 `submit.form.reason` が配列です。文字列が要ります"},
		{"submit_leave", submit("reason", `{}`),
			"The argument `submit.form.reason` of `start` is an object, and must be a string",
			"関数 `start` の引数 `submit.form.reason` がオブジェクトです。文字列が要ります"},
		{"submit_leave", submit("reason", `true`),
			"The argument `submit.form.reason` of `start` is true, and must be a string",
			"関数 `start` の引数 `submit.form.reason` が true です。文字列が要ります"},
		{"submit_leave", `{"comment":"x"}`,
			"The argument `submit.form` of `start` is missing, and must be an object",
			"関数 `start` の引数 `submit.form` がありません。オブジェクトが要ります"},
		{"submit_leave", `{"form":null}`,
			"The argument `submit.form` of `start` is null, and must be an object",
			"関数 `start` の引数 `submit.form` が null です。オブジェクトが要ります"},
		{"submit_leave", `{"form":` + form + `,"comment":5}`,
			"The argument `submit.comment` of `start` is 5, and must be a string",
			"関数 `start` の引数 `submit.comment` が 5 です。文字列が要ります"},
		{"approve", approve(`{"round":"1","stage":0,"edits":0}`),
			"The argument `event.approve.revision.round` of `next` is \"1\", and must be an integer",
			"関数 `next` の引数 `event.approve.revision.round` が \"1\" です。整数が要ります"},
		{"approve", approve(`{"round":1,"stage":0}`),
			"The argument `event.approve.revision.edits` of `next` is missing, and must be an integer",
			"関数 `next` の引数 `event.approve.revision.edits` がありません。整数が要ります"},
		{"approve", approve(`{"round":1,"stage":0,"edits":1e400}`),
			"The argument `event.approve.revision.edits` of `next` is outside int64",
			"関数 `next` の引数 `event.approve.revision.edits` が int64 の外にあります"},
		{"approve", approve(`[]`),
			"The argument `event.approve.revision` of `next` is an array, and must be an object",
			"関数 `next` の引数 `event.approve.revision` が配列です。オブジェクトが要ります"},
		{"resubmit_leave", `{"revision":` + rev + `,"form":{},"clear":[5]}`,
			"The argument `event.resubmit.clear[0]` of `next` is 5, and must be a string",
			"関数 `next` の引数 `event.resubmit.clear[0]` が 5 です。文字列が要ります"},
		{"resubmit_leave", `{"revision":` + rev + `,"form":{"first_day":"0000-01-01"}}`,
			"The argument `event.resubmit.form.first_day` of `next` is 0000-01-01, outside its range >=0001-01-01 <=9999-12-31",
			"関数 `next` の引数 `event.resubmit.form.first_day` の 0000-01-01 は、範囲 >=0001-01-01 <=9999-12-31 の外です"},
		{"edit_expense", `{"revision":` + rev + `,"fields":{"account":5}}`,
			"The argument `event.edit.fields.account` of `next` is 5, and must be a string",
			"関数 `next` の引数 `event.edit.fields.account` が 5 です。文字列が要ります"},
		{"resubmit_expense", `{"revision":` + rev + `,"form":{"items":{}}}`,
			"The argument `event.resubmit.form.items` of `next` is an object, and must be an array",
			"関数 `next` の引数 `event.resubmit.form.items` がオブジェクトです。配列が要ります"},
	} {
		op := a.ops[c.op]
		if op == nil {
			t.Fatalf("no operation %s", c.op)
		}
		err := op.checkBody([]byte(c.body))
		for _, l := range []struct{ lang, want string }{{"en", c.en}, {"ja", c.ja}} {
			r, rerr := checkFailed(err, op, l.lang)
			if rerr != nil || r.Outcome != Invalid || r.Problem != l.want {
				t.Errorf("%s %s in %s:\n got %s %q %v\nwant %q", c.op, c.body, l.lang, r.Outcome, r.Problem, rerr, l.want)
			}
		}
	}
	// What the entries take, the framework takes: a whole number in any spelling, a year of more
	// digits, and a key the form does not ask for left out of a change.
	for _, c := range []struct{ op, body string }{
		{"submit_leave", submit("days", `8.0`)},
		{"submit_leave", submit("days", `8e0`)},
		{"submit_leave", submit("days", `-0`)},
		{"submit_leave", submit("first_day", `"02026-12-21"`)},
		{"approve", approve(`{"round":1.0,"stage":0e0,"edits":-0.0}`)},
	} {
		if err := a.ops[c.op].checkBody([]byte(c.body)); err != nil {
			t.Errorf("%s %s: %v", c.op, c.body, err)
		}
	}
	// What the entries never see is said in the framework's own words, at its place in the body.
	for _, c := range []struct{ op, body, want string }{
		{"submit_leave", `{"form":` + with(form, "color", `"red"`) + `}`, `form: "color" is not one of its fields`},
		{"submit_leave", `[]`, "the body: object is expected"},
		{"submit_leave", `{`, "the body is not JSON: unexpected EOF"},
	} {
		r, err := checkFailed(a.ops[c.op].checkBody([]byte(c.body)), a.ops[c.op], "ja")
		if err != nil || r.Problem != c.want {
			t.Errorf("%s %s: %q %v, want %q", c.op, c.body, r.Problem, err, c.want)
		}
	}
}

// with is an object of JSON with a key set to a value written as JSON.
func with(object, key, value string) string {
	at := strings.Index(object, `"`+key+`":`)
	if at < 0 {
		return strings.TrimSuffix(object, "}") + `,"` + key + `":` + value + "}"
	}
	rest := object[at+len(key)+3:]
	end := strings.IndexAny(rest, ",}")
	return object[:at+len(key)+3] + value + rest[end:]
}
