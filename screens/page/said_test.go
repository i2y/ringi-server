package page

import (
	"reflect"
	"testing"
)

// TestSaidBlocks: the text a bundle holds is read as headings, paragraphs, lists, tables and blocks of
// code, with its comments left out.
func TestSaidBlocks(t *testing.T) {
	text := "<!-- Generated by ringi. This is a read-only rendering;\n  the source of truth is the .ringi file. -->\n" +
		"# Leave request: what changes\n\nThe request `leave` (v2 → v3):\n`leave.ringi` → `leave.ringi`\n\n" +
		"## Form\n\n| What | Before | After |\n|---|:--:|---|\n| First day | to 2027-12-31 | to 2028-12-31 |\n" +
		"| A \\| B | `a | b` | — |\n\n### Tickets\n\n- one\n- `two`\n\n```\n  kept  as is\n```\n#nota heading\n"
	want := []SaidBlock{
		{Heading: 1, Text: "Leave request: what changes"},
		{Text: "The request `leave` (v2 → v3): `leave.ringi` → `leave.ringi`"},
		{Heading: 2, Text: "Form"},
		{Head: []string{"What", "Before", "After"}, Rows: [][]string{{"First day", "to 2027-12-31", "to 2028-12-31"}, {"A | B", "`a | b`", "—"}}},
		{Heading: 2, Text: "Tickets"},
		{Items: []string{"one", "`two`"}},
		{Pre: "  kept  as is"},
		{Text: "#nota heading"},
	}
	if got := saidBlocks(text); !reflect.DeepEqual(got, want) {
		t.Errorf("the blocks:\n%#v\nwant\n%#v", got, want)
	}
	if got := saidBlocks("| only | a head |\n"); len(got) != 1 || len(got[0].Head) != 2 || len(got[0].Rows) != 0 {
		t.Errorf("a table of a head alone: %#v", got)
	}
	if got := saidBlocks("|---|\n"); len(got) != 0 {
		t.Errorf("a table of a separator alone: %#v", got)
	}
}

// TestSpans: code between backticks is code, and nothing of the text is read as HTML.
func TestSpans(t *testing.T) {
	for text, want := range map[string]string{
		"written by `ritsu ringi diff` against": "written by <code>ritsu ringi diff</code> against",
		"<b>`<i>`":                              "&lt;b&gt;<code>&lt;i&gt;</code>",
		"a lone ` stays":                        "a lone ` stays",
		"":                                      "",
	} {
		if got := string(spans(text)); got != want {
			t.Errorf("spans(%q) = %q, want %q", text, got, want)
		}
	}
}
